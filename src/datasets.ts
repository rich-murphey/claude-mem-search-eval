// The evaluation datasets, each pinned by revision and checked by hash, and
// loaded into one shape: documents of one or more parts (one embedding per
// part, as claude-mem embeds each part of an observation) grouped into
// claude-mem projects, and queries with their relevant and judged documents.
// Data is downloaded from Hugging Face into cache/, never redistributed here.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { asyncBufferFromFile, parquetReadObjects } from 'hyparquet';
import { distinctTurns, loadLongMemEvalS } from './longmemeval.ts';

export interface Doc {
  id: string;
  /** The claude-mem project the document belongs to. */
  project: string;
  /** Texts embedded one vector each, in order. */
  parts: string[];
}

export interface Query {
  id: string;
  text: string;
  /** Reported by type in the results (LongMemEval question type, memsearch query type, MIRACL language). */
  type: string;
  /** The project searched, or null when `candidates` lists the documents searched. */
  project: string | null;
  /** The documents this query searches when they are not a whole project (LongMemEval's haystacks). */
  candidates: string[] | null;
  relevant: Set<string>;
  /** Every document judged for this query, relevant or not; null when the dataset records no non-relevant judgments. */
  judged: Set<string> | null;
}

export interface Dataset {
  key: string;
  /** One line naming the data, its revision and its license, for results headers. */
  source: string;
  docs: Doc[];
  queries: Query[];
}

export const DATASETS = [
  'longmemeval-s',
  'memsearch-zh', 'memsearch-en',
  'miracl-en', 'miracl-zh', 'miracl-ko', 'miracl-ja',
] as const;
export type DatasetKey = typeof DATASETS[number];

async function fetchPinned(url: string, path: string, sha256: string): Promise<Buffer> {
  if (!existsSync(path)) {
    mkdirSync(path.replace(/\/[^/]+$/, ''), { recursive: true });
    const response = await fetch(url);
    if (!response.ok) throw new Error(`download failed: ${response.status} ${url}`);
    writeFileSync(path, Buffer.from(await response.arrayBuffer()));
  }
  const bytes = readFileSync(path);
  const sha = createHash('sha256').update(bytes).digest('hex');
  if (sha !== sha256) throw new Error(`${path} has sha256 ${sha}, expected ${sha256}`);
  return bytes;
}

async function longMemEval(): Promise<Dataset> {
  const questions = await loadLongMemEvalS();
  const docs: Doc[] = [];
  for (const row of distinctTurns(questions)) {
    if (row.turnIndex === 0) docs.push({ id: row.sessionId, project: 'longmemeval', parts: [] });
    docs[docs.length - 1].parts.push(row.content);
  }
  return {
    key: 'longmemeval-s',
    source: 'LongMemEval-S cleaned (xiaowu0162/longmemeval-cleaned @ 98d7416c, MIT)',
    docs,
    // Abstention questions have no relevant session. A haystack can list a
    // session twice (README, Data); it counts once.
    queries: questions.filter(q => !q.question_id.endsWith('_abs')).map(q => ({
      id: q.question_id,
      text: q.question,
      type: q.question_type,
      project: null,
      candidates: [...new Set(q.haystack_session_ids)],
      relevant: new Set(q.answer_session_ids),
      judged: null,
    })),
  };
}

