async function miracl(lang: 'en' | 'zh' | 'ko' | 'ja'): Promise<Dataset> {
  const read = async (kind: string): Promise<any[]> => {
    const name = `${lang}-${kind}.parquet`;
    const path = `cache/miracl/${name}`;
    await fetchPinned(
      `https://huggingface.co/datasets/mteb/MIRACLRetrievalHardNegatives/resolve/${MIRACL_REVISION}/${lang}-${kind}/dev-00000-of-00001.parquet`,
      path, MIRACL_SHA256[name],
    );
    return parquetReadObjects({ file: await asyncBufferFromFile(path) });
  };
  const [corpus, queries, qrels] = [await read('corpus'), await read('queries'), await read('qrels')];
  const relevant = new Map<string, Set<string>>(), judged = new Map<string, Set<string>>();
  for (const r of qrels) {
    const q = String(r['query-id']);
    if (!judged.has(q)) { judged.set(q, new Set()); relevant.set(q, new Set()); }
    judged.get(q)!.add(r['corpus-id']);
    if (Number(r.score) > 0) relevant.get(q)!.add(r['corpus-id']);
  }
  return {
    key: `miracl-${lang}`,
    source: `MIRACL ${lang} dev, human-judged, pooled corpus ` +
      `(mteb/MIRACLRetrievalHardNegatives @ ${MIRACL_REVISION.slice(0, 8)}, CC-BY-SA-4.0)`,
    // Passages embed as title and text together, as MTEB embeds them.
    docs: corpus.map(c => ({ id: c.id, project: `miracl-${lang}`, parts: [`${c.title ?? ''} ${c.text}`.trim()] })),
    queries: queries
      .filter(q => (relevant.get(String(q.id))?.size ?? 0) > 0)
      .map(q => ({
        id: String(q.id),
        text: q.text,
        type: lang,
        project: `miracl-${lang}`,
        candidates: null,
        relevant: relevant.get(String(q.id))!,
        judged: judged.get(String(q.id))!,
      })),
  };
}

export async function loadDataset(key: string): Promise<Dataset> {
  switch (key) {
    case 'longmemeval-s': return longMemEval();
    case 'memsearch-zh': return memsearch('zh');
    case 'memsearch-en': return memsearch('en');
    case 'miracl-en': return miracl('en');
    case 'miracl-zh': return miracl('zh');
    case 'miracl-ko': return miracl('ko');
    case 'miracl-ja': return miracl('ja');
    default: throw new Error(`unknown dataset ${key}; known: ${DATASETS.join(', ')}`);
  }
}

/** Every part of every document, in document order: the row order of a dataset's vector files. */
export function rowsOf(dataset: Dataset): Array<{ doc: string; part: number; text: string }> {
  return dataset.docs.flatMap(d => d.parts.map((text, part) => ({ doc: d.id, part, text })));
}

/** The documents each query searches: its candidates, or its project's documents. */
export function searchedDocs(dataset: Dataset): (q: Query) => string[] {
  const byProject = new Map<string, string[]>();
  for (const d of dataset.docs) {
    if (!byProject.has(d.project)) byProject.set(d.project, []);
    byProject.get(d.project)!.push(d.id);
  }
  return q => q.candidates ?? byProject.get(q.project!) ?? [];
}

export const contentHash = (text: string) => createHash('sha256').update(text).digest('hex').slice(0, 16);
