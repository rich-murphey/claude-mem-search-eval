async function memsearch(lang: 'zh' | 'en'): Promise<Dataset> {
  const read = async (name: string) => (await fetchPinned(
    `https://huggingface.co/datasets/zc277584121/memsearch-memory-retrieval/resolve/${MEMSEARCH_REVISION}/data/${name}`,
    `cache/memsearch/${name}`, MEMSEARCH_SHA256[name],
  )).toString('utf8').trim().split('\n').map(line => JSON.parse(line));
  const corpus = await read(`corpus_${lang}.jsonl`);
  const queries = await read(`queries_${lang}.jsonl`);
  return {
    key: `memsearch-${lang}`,
    source: `memsearch-memory-retrieval, ${lang === 'zh' ? 'Chinese (original)' : 'English (machine-translated from Chinese)'} ` +
      `(zc277584121/memsearch-memory-retrieval @ ${MEMSEARCH_REVISION.slice(0, 8)}, MIT); queries and labels generated by gpt-4o-mini`,
    docs: corpus.map((c: any) => ({ id: c.chunk_id, project: c.project, parts: [c.content] })),
    queries: queries.map((q: any) => ({
      id: q.query_id,
      text: q.query,
      type: q.query_type,
      project: q.source_project,
      candidates: null,
      relevant: new Set(q.positive_chunk_ids),
      judged: null,
    })),
  };
}

